DDL = """
CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE IF NOT EXISTS app.starts(
  start_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_map TEXT NOT NULL, faction TEXT NOT NULL,
  leader TEXT NOT NULL DEFAULT '', difficulty DOUBLE PRECISION,
  UNIQUE(campaign_map, faction, leader, difficulty));

CREATE TABLE IF NOT EXISTS app.experiments(
  experiment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE, config TEXT NOT NULL DEFAULT '{}',
  created_ts DOUBLE PRECISION NOT NULL, status TEXT NOT NULL DEFAULT 'stopped',
  note TEXT);

CREATE TABLE IF NOT EXISTS app.segments(
  segment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  experiment_id BIGINT NOT NULL REFERENCES app.experiments(experiment_id),
  seq INTEGER NOT NULL, started_ts DOUBLE PRECISION NOT NULL,
  code_version TEXT, note TEXT, params TEXT,
  UNIQUE(experiment_id, seq));

CREATE TABLE IF NOT EXISTS app.campaign_tags(
  campaign_key TEXT PRIMARY KEY,
  start_id BIGINT REFERENCES app.starts(start_id),
  experiment_id BIGINT REFERENCES app.experiments(experiment_id),
  segment_id BIGINT REFERENCES app.segments(segment_id));

CREATE TABLE IF NOT EXISTS app.boards(
  board_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE, ord INTEGER NOT NULL DEFAULT 0,
  created_ts DOUBLE PRECISION NOT NULL);

CREATE TABLE IF NOT EXISTS app.views(
  view_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  board_id BIGINT NOT NULL REFERENCES app.boards(board_id) ON DELETE CASCADE,
  name TEXT NOT NULL, spec TEXT NOT NULL, ord INTEGER NOT NULL DEFAULT 0,
  created_ts DOUBLE PRECISION NOT NULL);

CREATE TABLE IF NOT EXISTS app.settings(k TEXT PRIMARY KEY, v TEXT NOT NULL);

CREATE INDEX IF NOT EXISTS ix_segments_exp ON app.segments(experiment_id, seq);
CREATE INDEX IF NOT EXISTS ix_tags_exp ON app.campaign_tags(experiment_id);
CREATE INDEX IF NOT EXISTS ix_tags_start ON app.campaign_tags(start_id);
CREATE INDEX IF NOT EXISTS ix_views_board ON app.views(board_id, ord);
"""

